# PlatformIO pre-build script: stock web UI + OpenFW patches -> gzip -> src/web_index.h.
Import("env")  # noqa: F821
import gzip
import os
import sys

root = env.subst("$PROJECT_DIR")  # noqa: F821
sys.path.insert(0, os.path.join(root, "tools"))
import ui_i18n  # noqa: E402
import ui_patch  # noqa: E402

src = os.path.join(root, "web", "stock_index.html")
dst = os.path.join(root, "src", "web_index.h")
inputs = [src] + [os.path.join(root, "tools", f) for f in ("ui_patch.py", "ui_i18n.py", "embed_web.py")]

if not os.path.exists(dst) or os.path.getmtime(dst) < max(os.path.getmtime(p) for p in inputs):
    html = ui_i18n.apply(ui_patch.apply(open(src, encoding="utf-8").read()))
    data = gzip.compress(html.encode("utf-8"), 9, mtime=0)
    lines = ["  " + ",".join("0x%02x" % b for b in data[i:i + 20]) + "," for i in range(0, len(data), 20)]
    with open(dst, "w") as f:
        f.write("// Generated by tools/embed_web.py from web/stock_index.html + tools/ui_patch.py + tools/ui_i18n.py. Do not edit.\n")
        f.write("#pragma once\n#include <pgmspace.h>\n\n")
        f.write("static const uint8_t WEB_INDEX_GZ[] PROGMEM = {\n%s\n};\n" % "\n".join(lines))
        f.write("static const size_t WEB_INDEX_GZ_LEN = %d;\n" % len(data))
    print("embed_web: %s (%d bytes gz)" % (dst, len(data)))
