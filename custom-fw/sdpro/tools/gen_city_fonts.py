#!/usr/bin/env python3
"""Generate src/fonts/city_fonts.h: per-region fonts for the city name on the alert screen.

For every region label (city) in gen_ukraine_map.LABELS, picks the largest bold size at which the
city fits the screen width on its own line (capped by the line height). Each size holds only the
glyphs of the cities that use it (keeps flash small); regions sharing a size share the font.

Usage: gen_city_fonts.py <DejaVuSans-Bold.ttf> <out.h>
"""
import os
import sys

sys.path.insert(0, os.path.dirname(__file__))
from gen_ukraine_map import LABELS  # noqa: E402
from gen_vlw import c_array, render, text_width  # noqa: E402

WIDTH = 240 - 2 * 3  # screen minus side margins
MAX_SIZE = 40        # bottom line of the alert screen is ~45 px tall


def main(ttf, dst):
    sizes = [max(s for s in range(12, MAX_SIZE + 1) if text_width(ttf, s, c) <= WIDTH) for c in LABELS]
    total = 0
    with open(dst, "w", encoding="utf-8") as f:
        f.write("// Generated by tools/gen_city_fonts.py from %s. Do not edit.\n" % os.path.basename(ttf))
        f.write("// DejaVu fonts: Bitstream Vera license (free to embed and redistribute).\n")
        f.write("#pragma once\n#include <pgmspace.h>\n\n")
        glyphs = 0
        for s in sorted(set(sizes)):
            chars = set(" " + "".join(c for c, cs in zip(LABELS, sizes) if cs == s))
            glyphs += len(chars)
            data = render(ttf, s, chars)
            total += len(data)
            f.write(c_array("CITY_FONT_%d" % s, data))
        f.write("\n// Index = region (alerts.in.ua IoT order): font for the city name on its own line.\n")
        f.write("static const uint8_t *const CITY_FONT[] = {\n")
        f.write("".join("  CITY_FONT_%d,  // %s\n" % (s, c) for s, c in zip(sizes, LABELS)))
        f.write("};\n")
    print("%s: %d sizes, %d glyphs, %d bytes" % (dst, len(set(sizes)), glyphs, total))


if __name__ == "__main__":
    main(*sys.argv[1:3])
