# PlatformIO pre-build script: firmware version (SemVer) -> src/fw_version.h (FW_VERSION).
#
# VERSION (next to platformio.ini) holds the version being worked towards, X.Y.Z. A build from the
# commit that carries the release tag <custom_tag_prefix>X.Y.Z, with a clean tree, is that release:
# "1.1.0". Any other build is a pre-release of it: "1.1.0-dev+g<commit>", plus ".dirty" with
# uncommitted changes. So a device always shows whether it runs a release.
#
# Keep the copies in firmware/tools and sdpro/tools identical.
Import("env")  # noqa: F821
import os
import re
import subprocess

root = env.subst("$PROJECT_DIR")  # noqa: F821
prefix = env.GetProjectOption("custom_tag_prefix", "v")  # noqa: F821
version = open(os.path.join(root, "VERSION")).read().strip()
if not re.fullmatch(r"\d+\.\d+\.\d+", version):
    raise SystemExit("version.py: VERSION must be X.Y.Z, got %r" % version)


def git(*args):
    try:
        return subprocess.run(["git", *args], cwd=root, capture_output=True, text=True, check=True).stdout.strip()
    except (OSError, subprocess.CalledProcessError):
        return ""


commit = git("rev-parse", "--short", "HEAD")
dirty = bool(git("status", "--porcelain", "--", "."))
released = (prefix + version) in git("tag", "--points-at", "HEAD").split()
if released and not dirty:
    full = version
else:
    full = version + "-dev+" + ("g" + commit if commit else "unknown") + (".dirty" if dirty else "")

dst = os.path.join(root, "src", "fw_version.h")
text = ("// Generated by tools/version.py from VERSION and git. Do not edit.\n"
        "#pragma once\n#define FW_VERSION \"%s\"\n" % full)
if not os.path.exists(dst) or open(dst).read() != text:
    with open(dst, "w") as f:
        f.write(text)
print("version.py: FW_VERSION %s" % full)
