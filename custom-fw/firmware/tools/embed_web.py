# PlatformIO pre-build script: turns web/index.html.gz into src/web_index.h.
Import("env")  # noqa: F821
import os

root = env.subst("$PROJECT_DIR")  # noqa: F821
src = os.path.join(root, "web", "index.html.gz")
dst = os.path.join(root, "src", "web_index.h")

if not os.path.exists(dst) or os.path.getmtime(dst) < os.path.getmtime(src):
    data = open(src, "rb").read()
    lines = []
    for i in range(0, len(data), 20):
        lines.append("  " + ",".join("0x%02x" % b for b in data[i:i + 20]) + ",")
    with open(dst, "w") as f:
        f.write("// Generated by tools/embed_web.py from web/index.html.gz. Do not edit.\n")
        f.write("#pragma once\n#include <pgmspace.h>\n\n")
        f.write("static const uint8_t WEB_INDEX_GZ[] PROGMEM = {\n%s\n};\n" % "\n".join(lines))
        f.write("static const size_t WEB_INDEX_GZ_LEN = %d;\n" % len(data))
    print("embed_web: %s (%d bytes)" % (dst, len(data)))
