#!/usr/bin/env python3
"""Generate src/ukraine_map.h: oblast outlines projected to screen pixels.

Source: geoBoundaries UKR ADM1 (simplified), ODbL 1.0, (c) OpenStreetMap contributors.
  https://github.com/wmgeolab/geoBoundaries/raw/9469f09/releaseData/gbOpen/UKR/ADM1/geoBoundaries-UKR-ADM1_simplified.geojson

Usage: gen_ukraine_map.py <geoBoundaries-UKR-ADM1_simplified.geojson> <out.h>
Regions are indexed in alerts.in.ua IoT order, which the firmware uses everywhere.
"""
import json
import math
import sys

# alerts.in.ua IoT order -> geoBoundaries shapeName
REGIONS = [
    "Autonomous Republic of Crimea", "Volyn Oblast", "Vinnytsia Oblast", "Dnipropetrovsk Oblast",
    "Donetsk Oblast", "Zhytomyr Oblast", "Zakarpattia Oblast", "Zaporizhia Oblast",
    "Ivano-Frankivsk Oblast", "Kyiv", "Kyiv Oblast", "Kirovohrad Oblast", "Luhansk Oblast",
    "Lviv Oblast", "Mykolaiv Oblast", "Odessa Oblast", "Poltava Oblast", "Rivne Oblast",
    "Sevastopol", "Sumy Oblast", "Ternopil Oblast", "Kharkiv Oblast", "Kherson Oblast",
    "Khmelnytskyi Oblast", "Cherkasy Oblast", "Chernivtsi Oblast", "Chernihiv Oblast",
]
# Short Latin labels for the screen (TFT fonts have no Cyrillic).
LABELS = [
    "Crimea", "Volyn", "Vinnytsia", "Dnipro", "Donetsk", "Zhytomyr", "Zakarpattia", "Zaporizhzhia",
    "Ivano-Frankivsk", "Kyiv city", "Kyiv obl.", "Kirovohrad", "Luhansk", "Lviv", "Mykolaiv", "Odesa",
    "Poltava", "Rivne", "Sevastopol", "Sumy", "Ternopil", "Kharkiv", "Kherson", "Khmelnytskyi",
    "Cherkasy", "Chernivtsi", "Chernihiv",
]

# Screen box for the map (the rest of the 240x240 screen is header/footer).
BOX_X, BOX_Y, BOX_W, BOX_H = 2, 22, 236, 160
TOLERANCE_PX = 0.7


def rdp(points, eps):
    if len(points) < 3:
        return points
    (x1, y1), (x2, y2) = points[0], points[-1]
    dx, dy = x2 - x1, y2 - y1
    norm = math.hypot(dx, dy) or 1e-9
    idx, dmax = 0, 0.0
    for i in range(1, len(points) - 1):
        px, py = points[i]
        d = abs(dy * px - dx * py + x2 * y1 - y2 * x1) / norm if norm > 1e-9 else math.hypot(px - x1, py - y1)
        if d > dmax:
            idx, dmax = i, d
    if dmax <= eps:
        return [points[0], points[-1]]
    return rdp(points[: idx + 1], eps)[:-1] + rdp(points[idx:], eps)


def main(src, dst):
    feats = {f["properties"]["shapeName"]: f["geometry"] for f in json.load(open(src))["features"]}
    rings_ll = []
    for name in REGIONS:
        g = feats[name]
        polys = g["coordinates"] if g["type"] == "MultiPolygon" else [g["coordinates"]]
        rings_ll.append([ring for poly in polys for ring in poly])

    lons = [p[0] for r in rings_ll for ring in r for p in ring]
    lats = [p[1] for r in rings_ll for ring in r for p in ring]
    lon0, lon1, lat0, lat1 = min(lons), max(lons), min(lats), max(lats)
    kx = math.cos(math.radians((lat0 + lat1) / 2))
    scale = min(BOX_W / ((lon1 - lon0) * kx), BOX_H / (lat1 - lat0))
    ox = BOX_X + (BOX_W - (lon1 - lon0) * kx * scale) / 2
    oy = BOX_Y + (BOX_H - (lat1 - lat0) * scale) / 2

    def proj(p):
        return ((p[0] - lon0) * kx * scale + ox, (lat1 - p[1]) * scale + oy)

    points, rings, regions = [], [], []
    for r in rings_ll:
        first_ring = len(rings)
        sx = sy = n = 0
        for ring in r:
            pts = rdp([proj(p) for p in ring], TOLERANCE_PX)
            q = []
            for x, y in pts:
                xy = (int(round(x)), int(round(y)))
                if not q or q[-1] != xy:
                    q.append(xy)
            if len(q) < 3:
                continue
            rings.append((len(points), len(q)))
            points.extend(q)
            for x, y in q:
                sx, sy, n = sx + x, sy + y, n + 1
        regions.append((first_ring, len(rings) - first_ring, round(sx / n), round(sy / n)))

    with open(dst, "w") as f:
        f.write("// Generated by tools/gen_ukraine_map.py. Do not edit.\n")
        f.write("// Oblast outlines: geoBoundaries UKR ADM1, ODbL 1.0, (c) OpenStreetMap contributors.\n")
        f.write("#pragma once\n#include <stdint.h>\n\n")
        f.write("struct MapRing { uint16_t first, count; };\n")
        f.write("struct MapRegion { uint8_t firstRing, rings; uint8_t cx, cy; const char *label; };\n\n")
        f.write("static const int MAP_REGIONS = %d;\n" % len(regions))
        f.write("static const uint8_t MAP_POINTS[][2] = {\n")
        for i in range(0, len(points), 10):
            f.write("  " + "".join("{%d,%d}," % p for p in points[i:i + 10]) + "\n")
        f.write("};\nstatic const MapRing MAP_RINGS[] = {\n")
        f.write("".join("  {%d,%d},\n" % r for r in rings))
        f.write("};\n// Index = alerts.in.ua IoT order.\nstatic const MapRegion MAP[MAP_REGIONS] = {\n")
        for (fr, nr, cx, cy), label in zip(regions, LABELS):
            f.write('  {%d,%d,%d,%d,"%s"},\n' % (fr, nr, cx, cy, label))
        f.write("};\n")
    print("%s: %d regions, %d rings, %d points (%d bytes)" % (dst, len(regions), len(rings), len(points), 2 * len(points)))


if __name__ == "__main__":
    main(sys.argv[1], sys.argv[2])
