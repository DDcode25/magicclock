#!/usr/bin/env python3
"""Generate src/fonts/city_fonts.h: per-region fonts so "<city>   HH:MM" fits on one line.

For every region label (city) in gen_ukraine_map.LABELS, picks the largest bold size at which
city + gap + "00:00" fits the screen width. Each size holds only the glyphs of the cities that use
it plus the clock digits (keeps flash small); regions sharing a size share the font.

Usage: gen_city_fonts.py <DejaVuSans-Bold.ttf> <out.h>
"""
import os
import sys

sys.path.insert(0, os.path.dirname(__file__))
from gen_ukraine_map import LABELS  # noqa: E402
from gen_vlw import c_array, render, text_width  # noqa: E402

WIDTH = 240 - 2 * 3  # screen minus side margins
GAP = 8              # between city and clock
MAX_SIZE = 60        # footer under the map is ~76 px tall
CLOCK = "00:00"      # DejaVu digits are equal width, so any time has this width
CLOCK_CHARS = "0123456789:- "


def main(ttf, dst):
    sizes = [max(s for s in range(12, MAX_SIZE + 1) if text_width(ttf, s, c) + GAP + text_width(ttf, s, CLOCK) <= WIDTH)
             for c in LABELS]
    clock_only = max(s for s in range(12, MAX_SIZE + 1) if text_width(ttf, s, CLOCK) <= WIDTH // 2)
    total = 0
    with open(dst, "w", encoding="utf-8") as f:
        f.write("// Generated by tools/gen_city_fonts.py from %s. Do not edit.\n" % os.path.basename(ttf))
        f.write("// DejaVu fonts: Bitstream Vera license (free to embed and redistribute).\n")
        f.write("#pragma once\n#include <pgmspace.h>\n\n")
        glyphs = 0
        for s in sorted(set(sizes + [clock_only])):
            chars = set(CLOCK_CHARS + "".join(c for c, cs in zip(LABELS, sizes) if cs == s))
            glyphs += len(chars)
            data = render(ttf, s, chars)
            total += len(data)
            f.write(c_array("CITY_FONT_%d" % s, data))
        f.write("\n// Index = region (alerts.in.ua IoT order): font for \"<city> HH:MM\" on one line.\n")
        f.write("static const uint8_t *const CITY_FONT[] = {\n")
        f.write("".join("  CITY_FONT_%d,  // %s\n" % (s, c) for s, c in zip(sizes, LABELS)))
        f.write("};\n// No home region: clock alone, right half of the screen.\n")
        f.write("static const uint8_t *const CLOCK_FONT = CITY_FONT_%d;\n" % clock_only)
    print("%s: %d sizes, %d glyphs, %d bytes" % (dst, len(set(sizes + [clock_only])), glyphs, total))


if __name__ == "__main__":
    main(*sys.argv[1:3])
