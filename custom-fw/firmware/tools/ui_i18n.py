def _translate_markup(html):
    out, pos = [], 0
    for m in re.finditer(r"<(script|style)\b.*?</\1>", html, re.S):
        out.append(_markup_part(html[pos:m.start()]))
        out.append(m.group(0))
        pos = m.end()
    out.append(_markup_part(html[pos:]))
    return "".join(out)


def _markup_part(part):
    def text(m):
        lead, body, trail = re.match(r"(\s*)(.*?)(\s*)$", m.group(1), re.S).groups()
        return ">" + lead + HTML.get(body, body) + trail + "<"

    part = re.sub(r">([^<>]+)<", text, part)
    return re.sub(r'(placeholder|title|aria-label)="([^"]*)"', lambda m: '%s="%s"' % (m.group(1), HTML.get(m.group(2), m.group(2))), part)


def _translate_js(js):
    def lit(m):
        s = m.group(2)
        return m.group(1) + "'" + JS[s] + "'" if s in JS else m.group(0)

    return re.sub(r"((?<!name:)(?<!key:))'([^'\n]*)'", lit, js)


def apply(html):
    for a, b in RAW:
        if a not in html:
            raise RuntimeError("ui_i18n: raw anchor not found: " + a[:60])
        html = html.replace(a, b)
    html = _translate_markup(html)
    return re.sub(r"(<script>)(.*?)(</script>)", lambda m: m.group(1) + _translate_js(m.group(2)) + m.group(3), html, flags=re.S)
