#!/usr/bin/env python3
"""Generate an anti-aliased TFT_eSPI smooth font (VLW) as a C array, with Ukrainian Cyrillic.

Usage: gen_vlw.py <font.ttf> <pixel size> <symbol name> <out.h> [digits|numbers]
Glyphs: ASCII, Ukrainian/Russian Cyrillic and a few punctuation marks, or with "digits" only what a
clock needs (smaller). Rendered with Pillow/FreeType.
VLW layout (big-endian int32): header [count, version 11, size, 0, ascent, descent],
then per glyph [unicode, height, width, xAdvance, dY (top above baseline), dX, 0], then 8-bit bitmaps.
"""
import struct
import sys

from PIL import Image, ImageDraw, ImageFont

CHARS = (
    [chr(c) for c in range(0x20, 0x7F)]
    + [chr(c) for c in range(0x410, 0x450)]  # А..я
    + list("ЄІЇҐєіїґ’«»—–°…№")
)


DIGITS = list("0123456789:- ")
NUMBERS = list("0123456789+-.: ")  # signed decimals, e.g. "+18.5"


def render(ttf, size, chars, xscale=1.0):
    """VLW bytes for `chars` at `size` px; xscale < 1 narrows the glyphs (taller text in a given width)."""
    font = ImageFont.truetype(ttf, size)
    ascent, descent = font.getmetrics()
    metrics, bitmaps = [], []
    for ch in sorted(set(chars)):
        adv = round(font.getlength(ch) * xscale)
        x0, y0, x1, y1 = font.getbbox(ch, anchor="ls")
        w, h = max(0, x1 - x0), max(0, y1 - y0)
        if ch == " " or w == 0 or h == 0:
            metrics.append((ord(ch), 0, 0, adv, 0, 0))
            bitmaps.append(b"")
            continue
        img = Image.new("L", (w, h), 0)
        ImageDraw.Draw(img).text((-x0, -y0), ch, font=font, fill=255, anchor="ls")
        if xscale != 1.0:
            w = max(1, round(w * xscale))
            img = img.resize((w, h), Image.LANCZOS)
            x0 = round(x0 * xscale)
        metrics.append((ord(ch), h, w, adv, -y0, x0))
        bitmaps.append(img.tobytes())

    data = struct.pack(">6i", len(metrics), 11, size, 0, ascent, descent)
    for m in metrics:
        data += struct.pack(">7i", *m, 0)
    return data + b"".join(bitmaps)


def text_width(ttf, size, text, xscale=1.0):
    """Width as TFT_eSPI lays it out: sum of the rounded per-glyph advances."""
    font = ImageFont.truetype(ttf, size)
    return sum(round(font.getlength(c) * xscale) for c in text)


def c_array(name, data):
    lines = ["  " + ",".join("0x%02x" % b for b in data[i:i + 24]) + "," for i in range(0, len(data), 24)]
    return "static const uint8_t %s[] PROGMEM = {\n%s\n};\n" % (name, "\n".join(lines))


def main(ttf, size, name, dst, charset="full"):
    data = render(ttf, int(size), {"digits": DIGITS, "numbers": NUMBERS}.get(charset, CHARS))
    with open(dst, "w") as f:
        f.write("// Generated by tools/gen_vlw.py from %s, %s px. Do not edit.\n" % (ttf.split("/")[-1], size))
        f.write("// DejaVu fonts: Bitstream Vera license (free to embed and redistribute).\n")
        f.write("#pragma once\n#include <pgmspace.h>\n\n")
        f.write(c_array(name, data))
    print("%s: %d bytes" % (dst, len(data)))


if __name__ == "__main__":
    main(*sys.argv[1:6])
