#!/usr/bin/env python3
"""Generate src/fonts/font_alarm.h: the word "ТРИВОГА" for the alarm blink, as tall as fits.

The word is width-limited (bold 44 px fills the screen), so the glyphs are narrowed to XSCALE and the
size is the largest at which the word fits WIDTH.

Usage: gen_alarm_font.py <DejaVuSans-Bold.ttf> <out.h>
"""
import os
import sys

sys.path.insert(0, os.path.dirname(__file__))
from gen_vlw import c_array, render, text_width  # noqa: E402

WORD = "ТРИВОГА"
WIDTH = 240 - 2 * 4
XSCALE = 0.72  # narrower letters stay readable down to ~0.7


def main(ttf, dst):
    size = max(s for s in range(20, 120) if text_width(ttf, s, WORD, XSCALE) <= WIDTH)
    data = render(ttf, size, set(WORD + " "), XSCALE)
    with open(dst, "w", encoding="utf-8") as f:
        f.write("// Generated by tools/gen_alarm_font.py from %s, %d px x %.2f. Do not edit.\n" % (os.path.basename(ttf), size, XSCALE))
        f.write("// DejaVu fonts: Bitstream Vera license (free to embed and redistribute).\n")
        f.write("#pragma once\n#include <pgmspace.h>\n\n")
        f.write(c_array("FONT_ALARM_DATA", data))
    print("%s: %d px, %d bytes" % (dst, size, len(data)))


if __name__ == "__main__":
    main(*sys.argv[1:3])
